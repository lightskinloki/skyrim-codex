import { parseRoomDoc, type RoomDoc } from './document';
import type { Room } from './room';

/**
 * Where rooms come from. Three sources, one shape:
 *
 *   built-in  a JSON document in `src/battlemap/rooms/`, generated by
 *             `npm run rooms:export` from the procedural builders
 *   saved     a JSON document in this browser's localStorage
 *   imported  a JSON document the user picked; stored as a save
 *
 * Every entry is parsed on the way in, so the board never receives a room that
 * has not been through the validator — a hand-edited save cannot draw garbage.
 */

export type RoomEntry = {
  id: string;
  name: string;
  source: 'builtin' | 'saved';
  doc: RoomDoc;
  room: Room;
  /** Local only: when this browser last wrote the save. */
  savedAt?: number;
};

const PREFIX = 'skyrim-codex.room.v1.';
const LAST_KEY = 'skyrim-codex.room.last';

const BUILT_IN_DOCUMENTS: unknown[] = [
  tavernDoc,
  cavernDoc,
  ivarsteadDoc,
  innDoc,
  traderDoc,
  // Korvanjund, in play order (src/battlemap/korvanjund.ts).
  kvCausewayDoc, kvShaftDoc, kvArmoryDoc, kvEmbalmingDoc, kvDescentDoc, kvLandingDoc, kvCryptDoc, kvThroneDoc,
];

/** localStorage is absent in Node (the tests) and can throw in locked-down browsers. */
const store = (): Storage | null => {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage;
  } catch {
    return null;
  }
};

export function saveKey(id: string): string {
  return `${PREFIX}${id}`;
}

/**
 * The environment the table was last looking at. Reopening the board should
 * return to the room you left, not to whichever room happens to be first in
 * the list — with five environments shipped, the default is a coin toss.
 */
export function rememberRoom(id: string): void {
  const s = store();
  if (!s) return;
  try {
    s.setItem(LAST_KEY, id);
  } catch {
    /* a browser with storage switched off simply forgets */
  }
}

export function lastRoomId(): string | null {
  const s = store();
  if (!s) return null;
  try {
    return s.getItem(LAST_KEY);
  } catch {
    return null;
  }
}

/** Built-ins first, then this browser's saves, newest first. */
export function listLibrary(): RoomEntry[] {
  const out: RoomEntry[] = [];

  for (const source of BUILT_IN_DOCUMENTS) {
    const res = parseRoomDoc(source);
    if (res.status === 'bad') {
      console.error(`[rooms] a built-in room failed to parse: ${res.errors.map((e) => `${e.path} ${e.message}`).join('; ')}`);
      continue;
    }
    out.push({ id: res.doc.id, name: res.doc.name, source: 'builtin', doc: res.doc, room: res.room });
  }

  const s = store();
  if (!s) return out;

  const saves: RoomEntry[] = [];
  for (let i = 0; i < s.length; i++) {
    const key = s.key(i);
    if (!key || !key.startsWith(PREFIX)) continue;
    try {
      const envelope = JSON.parse(s.getItem(key) ?? '') as { doc?: unknown; savedAt?: unknown };
      const res = parseRoomDoc(envelope?.doc);
      if (res.status === 'bad') {
        console.error(
          `[rooms] ${key} is not a readable room, leaving it alone: ` +
            res.errors.map((e) => `${e.path} ${e.message}`).join('; '),
        );
        continue;
      }
      saves.push({
        id: res.doc.id,
        name: res.doc.name,
        source: 'saved',
        doc: res.doc,
        room: res.room,
        savedAt: typeof envelope.savedAt === 'number' ? envelope.savedAt : 0,
      });
    } catch {
      console.error(`[rooms] ${key} is not valid JSON, leaving it alone`);
    }
  }

  saves.sort((a, b) => (b.savedAt ?? 0) - (a.savedAt ?? 0));
  // A save with a built-in's id is an override, not a duplicate. Room ids are
  // what door links name, so one id must resolve to one room: the one the table
  // last edited. Delete the save to get the shipped document back.
  const savedIds = new Set(saves.map((s) => s.id));
  return [...out.filter((b) => !savedIds.has(b.id)), ...saves];
}

export function getRoom(id: string): RoomEntry | null {
  return listLibrary().find((r) => r.id === id) ?? null;
}

/**
 * Writes the save. Returns the error message, or null when it was written —
 * quota is a UI problem, not an exception. A bare string keeps the call site
 * from needing the boolean discriminant that this project's tsconfig cannot
 * narrow.
 */
export function saveDoc(doc: RoomDoc): string | null {
  const s = store();
  if (!s) return 'This browser does not allow local storage.';
  try {
    s.setItem(saveKey(doc.id), JSON.stringify({ doc, savedAt: Date.now() }));
    return null;
  } catch (e) {
    const name = e instanceof Error ? e.name : 'Error';
    return name === 'QuotaExceededError'
      ? 'Browser storage is full. Export a room and delete one you no longer need.'
      : 'Could not write the save to this browser.';
  }
}

export function deleteSave(id: string): void {
  const s = store();
  if (!s) return;
  try {
    s.removeItem(saveKey(id));
  } catch {
    console.error(`[rooms] could not delete ${id}`);
  }
  // The key is namespaced by id, but a document's own id is authoritative, so
  // also sweep any envelope that claims this room. Collect first: removing while
  // walking `key(i)` shifts every later index.
  const doomed: string[] = [];
  for (let i = 0; i < s.length; i++) {
    const key = s.key(i);
    if (!key || !key.startsWith(PREFIX)) continue;
    try {
      const env = JSON.parse(s.getItem(key) ?? '') as { doc?: { id?: string } };
      if (env?.doc?.id === id) doomed.push(key);
    } catch {
      /* an unreadable key is not ours to remove */
    }
  }
  for (const key of doomed) s.removeItem(key);
}
